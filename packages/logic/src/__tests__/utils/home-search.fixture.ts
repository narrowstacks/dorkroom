export const film = (
  slug: string,
  brand: string,
  name: string,
  colorType: string,
  isoSpeed: number,
  reciprocityFailure: string | null,
  discontinued = false,
  aliases: Film['aliases'] = []
): Film => ({
  id: 0,
  uuid: `film-${slug}`,
  slug,
  brand,
  name,
  colorType,
  isoSpeed,
  grainStructure: null,
  description: '',
  manufacturerNotes: null,
  reciprocityFailure,
  discontinued,
  staticImageUrl: null,
  aliases,
  baseFilmSlug: null,
  dateAdded: '',
  createdAt: '',
  updatedAt: '',
});

export const developer = (
  slug: string,
  manufacturer: string,
  name: string,
  dilutions: [id: string, dilution: string][]
): Developer => ({
  id: 0,
  uuid: `developer-${slug}`,
  slug,
  name,
  manufacturer,
  type: 'concentrate',
  description: '',
  filmOrPaper: true,
  dilutions: dilutions.map(([id, dilution]) => ({
    id,
    name: dilution,
    dilution,
  })),
  mixingInstructions: null,
  storageRequirements: null,
  safetyNotes: null,
  notes: null,
  createdAt: '',
  updatedAt: '',
});

const recipe = (
  uuid: string,
  filmSlug: string,
  developerSlug: string,
  shootingIso: number,
  dilutionId: string | null,
  temperatureC: number,
  timeMinutes: number,
  agitationMethod: string,
  tag: string,
  infoSource: string
): Combination => ({
  id: 0,
  uuid,
  name: '',
  filmStockId: filmSlug,
  filmSlug,
  developerId: developerSlug,
  developerSlug,
  shootingIso,
  dilutionId,
  customDilution: null,
  temperatureC,
  temperatureF: Math.round(((temperatureC * 9) / 5 + 32) * 10) / 10,
  timeMinutes,
  agitationMethod,
  agitationSchedule: null,
  pushPull: null,
  tags: [tag],
  notes: null,
  infoSource,
  createdAt: '',
  updatedAt: '',
});

